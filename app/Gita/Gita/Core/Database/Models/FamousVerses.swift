    /// Whether a verse is one of them.
    static func contains(chapter: Int, sutra: Int) -> Bool {
        all.contains(Reference(chapter, sutra))
    }

    /// A chapter and verse number, and nothing else.
    struct Reference: Hashable, Sendable {
        let chapter: Int
        let sutra: Int

        init(_ chapter: Int, _ sutra: Int) {
            self.chapter = chapter
