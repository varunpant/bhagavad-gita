import Foundation

/// The eighty verses most people arrive already knowing.
///
/// Eighty of 701 is a marker on one verse in nine, and `FamousVersesTests`
/// holds it under one in eight — seven entries of headroom, which is close
/// enough that the next addition should come with a deletion. The rarer the
/// ring, the more it says.
///
/// A property of the **text**, not of the reader — which is what keeps it out
/// of `user.sqlite` and out of `ReadingProgress`. Nothing here changes, nothing
/// is earned, and nothing is reset; it is the same list on a first launch as on
/// the thousandth, so it belongs beside the corpus as a constant.
///
/// Held here rather than as a column in `gita.sqlite` for one reason: the
/// database is generated by `tools/build_db.py` from `srimad.csv`, and this is
/// editorial judgement rather than scraped data. Putting it in the schema would
/// mean a rebuild of the bundled database — and a review of the generator — to
/// change one opinion about which verses are well known.
///
/// Chapter and verse rather than row id, because that is how the list is
/// discussed, quoted and checked; ids are an implementation detail of the
/// build and would silently rot if the corpus were ever renumbered.
/// `nonisolated` because `Verse` is: the models are `Sendable` structs that
/// cross the database boundary on whatever thread GRDB hands them over on, and
/// a constant they consult cannot be main-actor only. Nothing here is mutable,
